#at the heart of every if statement is an expresion that can be evaluated as TRUE or FALSE
#it is called CONDITIONAL TEST
#PYTHON uses the values TRUE and FALSE to decide whether the code in an if statement should be executed
#if conditional test evaluates to TRUE, Python executesbthe code following the if statement
#if the test evaluates to FALSE, Python ignores the code following the if statement

#CHECKING FOR EQUALITY
#most conditional tests compare current value of variable to a specific value of interest
#the simplest conditional test checks whether the value of a variable is equal to the value of interest:
"""
>>> car = 'bmw'
>>> car == 'bmw'
True
"""
#the first line sets the value of car to 'bmw' using equal sign
#next line checks whether value of car is 'bmw' with DOUBLE SIGN(==)
#this EQUALITY OPERATOR returns TRUE if the values on the left and right side of OPERATOR match
#FALSE if they dont match