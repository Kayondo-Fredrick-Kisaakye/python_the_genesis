#to reverse the original order of a list, you can use REVERSE() METHOD
#if we originally stored the list of cars in chronological order according to when we bought them,
#we could easily rearrange the list into REVERSE-CHRONOLOGICAL order

cars = ['fortuner', 'cruiser 76', 'mazda mx5', 'alphard']
print(cars)  #['fortuner', 'cruiser 76', 'mazda mx5', 'alphard']

cars.reverse()
print(cars)  #['alphard', 'mazda mx5', 'cruiser 76', 'fortuner']